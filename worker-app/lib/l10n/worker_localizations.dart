  /// Translates key with safe English fallback and dynamic argument interpolation.
  String translate(String key, {Map<String, String>? params}) {
    final lang = locale.languageCode;
    String? value = _localizedValues[lang]?[key] ?? _localizedValues['en']?[key];

    if (value == null) {
      return key; // Safe fallback to key if not found
    }

    if (params != null && params.isNotEmpty) {
      params.forEach((paramKey, paramVal) {
        value = value!.replaceAll('{$paramKey}', paramVal);
      });
    }

    return value!;
  }

  /// Shorthand translation method.
  String tr(String key, {Map<String, String>? params}) => translate(key, params: params);

  // Parameterized Helpers
  String otpSubtitle(String phone) => tr('otp_subtitle', params: {'phone': phone});
  String resendIn(int seconds) => tr('resend_in', params: {'seconds': seconds.toString()});
  String expiresIn(int seconds) => tr('expires_in', params: {'seconds': seconds.toString()});
